#ifndef POSTMACHINE_H
#define POSTMACHINE_H

#include <vector>
#include <iostream>

/**
 * @brief Класс машины Поста с лентой целых чисел.
 *
 * Хранит ленту ячеек, позицию головки и признак остановки.
 * Лента эмулируется вектором: при выходе за правый край она растёт
 * (push_back), при сдвиге влево с нулевой позиции — расширяется влево
 * (insert). Класс не знает ничего о пользовательском интерфейсе —
 * только логика машины.
 */
class PostMachine {
private:
    std::vector<int> tape;  ///< Лента машины (ячейки целых чисел)
    int headPos;            ///< Индекс ячейки, на которой стоит головка
    bool halted;            ///< true, если машина остановлена

public:
    /**
     * @brief Конструктор по умолчанию.
     * Создаёт ленту из 10 нулей, головка на позиции 0, машина не остановлена.
     */
    PostMachine();

    /**
     * @brief Конструктор с начальной лентой и позицией головки.
     * @param initialTape Начальное содержимое ленты.
     * @param startPos Начальная позиция головки. Отрицательное значение
     *        зажимается в 0, значение за правым краем расширяет ленту до startPos + 1.
     */
    PostMachine(const std::vector<int>& initialTape, int startPos);

    /**
     * @brief Конструктор копирования.
     * @param other Машина, с которой снимается копия.
     */
    PostMachine(const PostMachine& other);

    /**
     * @brief Деструктор.
     */
    ~PostMachine();

    /**
     * @brief Оператор присваивания копированием.
     * @param other Машина-источник.
     * @return Ссылка на текущий объект.
     */
    PostMachine& operator=(const PostMachine& other);

    /**
     * @brief Оператор сравнения на равенство.
     * @param other Машина для сравнения.
     * @return true, если совпадают лента, позиция головки и признак остановки.
     */
    bool operator==(const PostMachine& other) const;

    /**
     * @brief Оператор сравнения на неравенство.
     * @param other Машина для сравнения.
     * @return true, если машины различаются.
     */
    bool operator!=(const PostMachine& other) const;

    /**
     * @brief Оператор вывода машины в поток.
     * Печатает ленту, выделяя ячейку под головкой квадратными скобками,
     * и состояние (HALTED или RUNNING).
     * @param os Поток вывода.
     * @param machine Машина для вывода.
     * @return Ссылка на поток.
     */
    friend std::ostream& operator<<(std::ostream& os, const PostMachine& machine);

    /**
     * @brief Оператор ввода машины из потока.
     * Ожидает размер ленты, позицию головки и затем элементы ленты.
     * @param is Поток ввода.
     * @param machine Машина, в которую считывается состояние.
     * @return Ссылка на поток.
     */
    friend std::istream& operator>>(std::istream& is, PostMachine& machine);

    /**
     * @brief Сдвигает головку влево.
     * Если головка не на нулевой позиции — уменьшает её индекс.
     * На нулевой позиции лента расширяется влево (ячейка вставляется в начало).
     * Игнорируется, если машина остановлена.
     */
    void moveLeft();

    /**
     * @brief Сдвигает головку вправо.
     * Если головка выходит за правую границу — лента расширяется на одну ячейку.
     * Игнорируется, если машина остановлена.
     */
    void moveRight();

    /**
     * @brief Записывает значение в ячейку под головкой.
     * @param value Значение 0 или 1; другие значения игнорируются.
     *        Вызов после остановки машины также игнорируется.
     */
    void write(int value);

    /**
     * @brief Останавливает машину.
     * После остановки команды сдвига и записи игнорируются.
     */
    void halt();

    /**
     * @brief Возвращает позицию головки.
     * @return Индекс ячейки под головкой.
     */
    int getHeadPos() const;

    /**
     * @brief Возвращает значение ячейки по индексу.
     * @param index Индекс ячейки.
     * @return Значение ячейки или 0, если индекс за пределами ленты.
     */
    int getCell(int index) const;

    /**
     * @brief Проверяет, остановлена ли машина.
     * @return true, если машина остановлена.
     */
    bool isHalted() const;

    /**
     * @brief Возвращает текущий размер ленты.
     * @return Количество ячеек ленты.
     */
    int getTapeSize() const;
};

#endif
